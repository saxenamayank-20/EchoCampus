"""Writes docs/graphs.md: the intake and closure graphs as Mermaid diagrams, drawn by langgraph itself.

Run from the repo root:  python scripts/export_graphs.py
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from backend.app.agents.closure_graph import build_closure_graph
from backend.app.agents.intake_graph import build_intake_graph

OUT = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "docs", "graphs.md")


def main() -> None:
    # no service: the nodes never run, we only need the shape
    intake = build_intake_graph(None).get_graph().draw_mermaid()
    closure = build_closure_graph(None).get_graph().draw_mermaid()
    with open(OUT, "w") as f:
        f.write("# EchoCampus graphs\n\nGenerated by `python scripts/export_graphs.py` from the LangGraph code.\n\n")
        f.write("## Intake (submitting a complaint)\n\nDotted arrows are conditional (Critical or not).\n\n")
        f.write(f"```mermaid\n{intake}```\n\n")
        f.write("## Closure (human in the loop)\n\n`await_student` and `await_admin` pause the graph until a "
                "person answers. The paused state is saved in Postgres.\n\n")
        f.write(f"```mermaid\n{closure}```\n")
    print(f"[GRAPHS] written to {OUT}")


if __name__ == "__main__":
    main()
